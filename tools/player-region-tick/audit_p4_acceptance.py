TOOLS = Path(__file__).resolve().parent
REPO = TOOLS.parents[1]
P3_VERIFY = {'xp': 'verify_worker_xp_removal', 'item': 'verify_worker_item_pickup',
             'chest': 'verify_worker_shared_chest', 'score': 'verify_worker_scoreboard',
             'map': 'verify_worker_backpack_map', 'damage': 'verify_worker_starvation_damage',
             'damage-foreign': 'verify_worker_starvation_damage'}
P4_VERIFY = {'routes': ('verify_owner_routes', 'owner-routes'),
             'async': ('verify_owner_async', 'owner-async'),
             'queue': ('verify_packet_queue', 'packet-queue'),
             'hotbar': ('verify_owner_packet', 'owner-packet')}


def require(ok, message):
    if not ok:
        raise AssertionError(message)


def load(path):
    return json.loads(Path(path).read_text())


def sha(path):
    result = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            result.update(chunk)
    return result.hexdigest()


def record(path):
    path = Path(path).resolve()
    return dict(path=str(path.relative_to(REPO)), sha256=sha(path), bytes=path.stat().st_size)


def command(path):
    result = load(path / 'result.json')
    require(result.get('exit') == 0 and result.get('argv'), 'No successful actual command ' + str(path))
    return result


def audit(args):
    product = args.product_root.resolve()
    evidence = load(args.evidence_map)
    manifest_path = REPO / evidence['manifest']
    manifest, _ = read_manifest(manifest_path)
    version = evidence['version']
    require(manifest['version'] == version, 'Wrong product manifest')
    installer = product / 'artifacts' / f'neoforge-{version}-installer.jar'
    require(sha(installer) == manifest['installerSha256'], 'Wrong final installer')
    for name, digest in manifest['review']['sources'].items():
        require(sha(REPO / name) == sha(product / 'source' / name) == digest, 'Production changed after freeze ' + name)
    for path in evidence['checks']:
        command(REPO / path)
    junit = load(product / 'junit-audit.json')
    require(junit['status'] == 'passed' and junit['tests'] == 652 and junit['classes'] == 21
            and junit['failures'] == junit['errors'] == junit['skipped'] == junit['unexpectedBackgroundExceptions'] == 0,
            'Final complete JUnit audit failed')
    files = list((product / 'regression-01/xml').glob('TEST-*.xml'))
    require(len(files) == 21 and all(sum(int(ET.parse(f).getroot().get(k, 0)) for f in files) == junit[k]
                                    for k in ['tests', 'failures', 'errors', 'skipped']), 'JUnit original XML differs')
    command(product / 'regression-01')
    require('BUILD SUCCESSFUL' in (product / 'regression-01/stdout.log').read_text(), 'No successful actual final Gradle run')
    spatial = ET.parse(product / 'regression-01/xml/TEST-net.neoforged.neoforge.unittest.RegionPlayerSpatialLeaseTest.xml').getroot()
    bounded = next((c for c in spatial.findall('testcase') if c.get('name') == 'originalPacketUtilsExecutorDoesNotAccumulateEmptyTasksAfterExplicitTerminal()'), None)
    require(bounded is not None and bounded.find('failure') is None and bounded.find('error') is None, 'Original PacketUtils executor bound regression missing')
    game_xml = list((product / 'gametest-server/tests').glob('*.junit.xml'))
    require(len(game_xml) == 1, 'Missing unique original GameTest XML')
    cases = ET.parse(game_xml[0]).getroot().findall('.//testcase')
    selected = {'physicalEntitySectionCrossing', 'blockEntityOwnerOperations', 'unsafeTickerForcesWholeRegionFallback'}
    require({c.get('name') for c in cases if c.find('passed') is not None} >= selected
            and all(c.find('failure') is None and c.find('error') is None for c in cases), 'Selected GameTests failed')
    patches = load(product / 'patch-proof.json')
    require(patches['status'] == 'passed' and patches['fileCount'] == 12, 'Missing strict persisted patch proof')
    require(sha(REPO / patches['archive']) == patches['archiveSha256'], 'Strict patch archive changed')
    with zipfile.ZipFile(REPO / patches['archive']) as archive:
        for row in patches['files']:
            require(sha(REPO / row['patch']) == row['patchSha256'] and sha(REPO / row['generated']) == row['sourceSha256'], 'Patch/generated bytes changed')
            name = row['generated'].split('/src/main/java/', 1)[1]
            require(hashlib.sha256(archive.read(name)).hexdigest() == row['sourceSha256'], 'Applied patch differs')
    roots, verdicts, accepted_commands, controls, reverified = set(), [], [], [], []

    def control(path, category):
        command(path)
        result = load(path / 'stdout.log')
        require(result['status'] == 'passed' and result['negativeControls'] > 0
                and result['negativeControls'] == len(result['controls'])
                and all(r['status'] == 'rejected' for r in result['controls']), 'Failed proof controls ' + str(path))
        controls.append(dict(category=category, command=record(path / 'result.json'), negativeControls=result['negativeControls']))
        accepted_commands.append(path / 'result.json')

    require(set(evidence['p2']) == set(P2_COMMAND_COUNTS), 'Incomplete P2 suite selection')
    schemas = {3: 0, 4: 0}
    for suite, count in P2_COMMAND_COUNTS.items():
        matrix = REPO / evidence['p2'][suite]
        result = load(matrix / 'matrix-result.json')
        require(result['status'] == 'passed' and result['suite'] == suite and len(result['commands']) == count, 'Incomplete P2 suite ' + suite)
        require(len({r['label'] for r in result['commands']}) == count, 'Repeated P2 command')
        for row in result['commands']:
            path = matrix / row['label']
            require(row['exit'] == 0, 'Failed accepted P2 command')
            command(path)
            accepted_commands.append(path / 'result.json')
            if row['label'].startswith(('controls-', 'phase-controls-')):
                control(path, 'p2-' + suite)
        for root in matrix.glob('server-*'):
            roots.add(root)
            paths = list(root.glob('*/independent-verdict*.json'))
            if suite == 'functional':
                paths.append(root / 'phase-order.json')
            require(paths, 'No independent P2 verdict ' + str(root))
            for path in paths:
                result = load(path)
                expected = 'passed_expected_failure' if suite in ['fault', 'same-group'] else 'passed'
                require(result['status'] == expected, 'Failed mapped P2 verdict ' + str(path))
                if expected == 'passed_expected_failure':
                    require(result['sameGroup'] == (suite == 'same-group') and result['failedInvocation']['worker']
                            and result['failedInvocation']['state'] == 'JOINED', 'Original fault did not really join')
                if suite == 'functional' and path.name != 'phase-order.json':
                    require(result['installerSha256'] == manifest['installerSha256'], 'Wrong schema product')
                    schemas[result['schema']] += result['scenarioCount']
                verdicts.append(record(path))
    require(schemas == {3: 144, 4: 180}, 'Original schema 3/4 incomplete')
    require(len(evidence['p3']) == 28 and {(r['kind'], r['mode']) for r in evidence['p3']} == {(k, m) for k in KINDS for m in MODES}, 'Incomplete P3 four-mode regression')
    expected_p4 = {(k, m) for k in ['routes', 'async', 'hotbar'] for m in MODES} | {('queue', m) for m in MODES if m.startswith('on')}
    require(len(evidence['p4']) == 14 and {(r['kind'], r['mode']) for r in evidence['p4']} == expected_p4, 'Incomplete P4 protocol matrix')
    for phase in ['p3', 'p4']:
        for case in evidence[phase]:
            root = REPO / case['root']
            kind, mode = case['kind'], case['mode']
            roots.add(root)
            stages = set()
            for stage, path in case['commands'].items():
                path = REPO / path
                stages.add(stage)
                command(path)
                accepted_commands.append(path / 'result.json')
                if stage == 'controls':
                    control(path, phase + '-' + kind)
            require(stages >= {'install', 'run', 'verify'}, 'Incomplete actual case commands ' + str(root))
            if mode == 'on-fixed' and kind != 'damage-foreign':
                require('controls' in stages, 'Missing positive-corpus proof controls')
            path = REPO / case['verdict']
            result = load(path)
            require(result['status'] == 'passed' and result['version'] == version
                    and result['requested'] == mode.startswith('on') and result['persistent'] == mode.endswith('persistent'), 'Wrong mapped product/mode')
            module = P3_VERIFY[kind] if phase == 'p3' else P4_VERIFY[kind][0]
            fresh = importlib.import_module(module).verify(root.resolve(), installer)
            require(fresh == result, 'Final strengthened verifier differs from mapped verdict ' + str(path))
            reverified.append(dict(phase=phase, kind=kind, mode=mode, verdict=record(path), result=fresh))
            verdicts.append(record(path))
    require(set(evidence['supplementalControls']) == {'network-overflow', 'socket', 'transition', 'timer', 'lifecycle', 'phase'}, 'Incomplete supplemental controls')
    for category, path in evidence['supplementalControls'].items():
        control(REPO / path, 'p2-' + category)
    require(len(roots) == 102, 'Unexpected number of unique isolated accepted installations')
    diagnostics = evidence.get('diagnosticCorpora', [])
    require(len(diagnostics) == 2, 'Missing the two additional strict persistent foreign-damage probes')
    diagnostic_roots = set()
    for case in diagnostics:
        root = REPO / case['root']
        diagnostic_roots.add(root)
        for path in case['commands'].values():
            command(REPO / path)
            accepted_commands.append(REPO / path / 'result.json')
        actual = importlib.import_module('verify_worker_starvation_damage').verify(root.resolve(), installer)
        require(actual == load(REPO / case['verdict']) and actual['foreignWatcher'] and actual['persistent'] and actual['requested'], 'Additional diagnostic probe did not strictly pass')
        reverified.append(dict(phase='diagnostic', kind='damage-foreign', mode='on-persistent', verdict=record(REPO / case['verdict']), result=actual))
    stall = evidence['preservedProbeStall']
    require(stall['accepted'] is False and load(REPO / stall['run'] / 'result.json')['exit'] == 1, 'Original unexplained probe stall was erased or accepted')
    stalled_result = load(REPO / stall['root'] / 'worker-starvation-damage/result.json')
    require(stalled_result['status'] == 'failed' and stalled_result['serverExits'] == [-9] and 'timed out' in stalled_result['error'], 'Original stalled corpus changed')
    require(load(REPO / stall['root'] / 'worker-starvation-damage/debugger/result.json')['exit'] == 0, 'Original completed debugger evidence changed')
    seed = REPO / 'tmp/player-region-tick-p3-01/server-on-fixed-01/libraries'
    seed_hashes = load(REPO / 'tmp/player-region-tick-p3-01/seed-library-hashes.json')
    for name, digest in seed_hashes.items():
        require(sha(seed / name) == digest, 'Seed library changed ' + name)
    private_inodes, isolation = set(), []
    for root in sorted(roots | diagnostic_roots):
        install = load(root / 'installation.json')
        require(install['version'] == version and install['installerSha256'] == manifest['installerSha256'] and install['installerInputsPrivate'], 'Wrong/unsafe installation')
        for suffix, digest in manifest['installedJars'].items():
            path = root / f'libraries/net/neoforged/neoforge/{version}/neoforge-{version}-{suffix}.jar'
            require(sha(path) == digest, 'Wrong actual installed core')
        checked = 0
        for path in (root / 'libraries').rglob('*.jar'):
            relative = str(path.relative_to(root / 'libraries'))
            if not relative.startswith(('net/minecraft/', 'net/neoforged/neoforge/')):
                continue
            identity = (path.stat().st_dev, path.stat().st_ino)
            require(identity not in private_inodes and (not (seed / relative).exists()
                    or identity != ((seed / relative).stat().st_dev, (seed / relative).stat().st_ino)), 'Shared mutable core/Minecraft inode')
            private_inodes.add(identity)
            checked += 1
        isolation.append(dict(server=str(root.relative_to(REPO)), privateCoreMinecraftJars=checked, linkedDependencies=install.get('linkedLibraryDependencies', 0)))
    for name in ['region-threading/PLAYER-WORKER-EXECUTION-AUDIT.md', 'region-threading/PLAYER-REGION-TICK-DESIGN.zh.md',
                 'tests/src/junit/java/net/neoforged/neoforge/unittest/RegionThreadingDeclarationsTest.java',
                 'tools/player-region-tick/verify_interactions.py', 'tools/player-region-tick/verify_resources.py',
                 'src/main/java/net/neoforged/neoforge/common/ForgiaConfig.java',
                 'src/main/java/net/neoforged/neoforge/server/threading/region/RegionThreadingConfig.java']:
        require(subprocess.check_output(['git', 'show', 'HEAD:' + name], cwd=REPO) == (REPO / name).read_bytes(), 'Protected default/hash gate/design source changed ' + name)
    processes = subprocess.check_output(['ps', '-eo', 'pid,args'], text=True)
    alive = [line for line in processes.splitlines() if '/player-region-tick-p4-' in line and
             (('bin/java ' in line) or ('node ' in line and any(n in line for n in ['clients.cjs', 'network_client.cjs'])))]
    require(not alive, 'Owned servers/clients still alive ' + str(alive))
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    sources = set(subprocess.check_output(['git', 'diff', '--name-only'], cwd=REPO, text=True).splitlines())
    sources.update(subprocess.check_output(['git', 'ls-files', '--others', '--exclude-standard'], cwd=REPO, text=True).splitlines())
    source_index = []
    for name in sorted(sources):
        path = REPO / name
        require(path.is_file(), 'Missing retained changed source')
        target = output / 'source' / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
        source_index.append(dict(source=name, snapshot=str(target.relative_to(REPO)), sha256=sha(path)))
    history = []
    for directory in sorted((REPO / 'tmp').glob('player-region-tick-p4-*')):
        for path in sorted(directory.rglob('command.json')):
            result_path = path.with_name('result.json')
            result = load(result_path) if result_path.exists() else None
            own = result is None and load(path).get('pid') == os.getppid()
            history.append(dict(command=record(path), result=record(result_path) if result else None,
                                exit=result.get('exit') if result else None,
                                acceptance='current_audit_wrapper_read_its_final_result' if own else 'unknown_exit_not_accepted' if result is None else 'preserved_actual_exit'))
    failures = [r for r in history if r['exit'] != 0 and r['acceptance'] != 'current_audit_wrapper_read_its_final_result']
    inputs = set(accepted_commands) | {installer, manifest_path, args.evidence_map.resolve()}
    for command_path in accepted_commands:
        inputs.update(p for p in command_path.parent.rglob('*') if p.is_file())
    for root in roots | diagnostic_roots | {REPO / stall['root']}:
        inputs.update(p for p in root.rglob('*') if p.is_file() and not set(p.relative_to(root).parts).intersection({'libraries', '.cache'}))
    for label in ['regression-01', 'gametest-command', 'gametest-server/tests', 'static-command', 'junit-audit-command']:
        inputs.update(p for p in (product / label).rglob('*') if p.is_file())
    inputs.update(p for p in product.iterdir() if p.is_file() and p.suffix in ['.json', '.py'])
    indexes = dict(inputs=[record(p) for p in sorted(inputs)], sources=source_index, isolation=isolation,
                   acceptedCommands=[record(p) for p in sorted(set(accepted_commands))], commandHistory=history,
                   preservedNonzeroOrUnknownCommands=failures, proofControls=controls, freshlyReverified=reverified)
    for name, value in indexes.items():
        (output / (name + '.json')).write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n')
    receipt = dict(schema=1, status='P4_complete_design_section_7_bounded_owner_network_protocols',
                   generatedAt=datetime.datetime.now(datetime.timezone.utc).isoformat(), version=version,
                   overallStatus='partial_P5_not_started', p4Status='complete_bounded_protocols', p5Status='not_started', stopBeforeP5=True,
                   installer=record(installer), manifest=record(manifest_path), evidenceMap=record(args.evidence_map.resolve()),
                   junit={k: junit[k] for k in ['tests', 'failures', 'errors', 'skipped']}, selectedGameTestsPassed=3,
                   persistedPatchProof=record(product / 'patch-proof.json'), schema3Scenarios=144, schema4Scenarios=180,
                   independentVerdicts=len(verdicts), acceptedIsolatedInstallations=len(roots),
                   p3Corpora=28, p4Corpora=14, p2Suites=evidence['p2'], proofNegativeControls=sum(r['negativeControls'] for r in controls),
                   seedJarHashesUnchanged=len(seed_hashes), preservedNonzeroOrUnknownCommands=len(failures),
                   additionalStrictDiagnosticCorpora=len(diagnostics), preservedUnexplainedProbeStall=stall,
                   indexes={name: record(output / (name + '.json')) for name in indexes},
                   supportedScope='Original bounded hotbar/unobstructed movement/matching teleport confirmation/plain inventory/shared single chest quickMove and unsigned low-spam ordered filtered-chat completion at current owner; original server fences and physical joins',
                   limitations=['One original packet/continuation joins at its original executor position; no new packet concurrency or speedup claim',
                                'One original persistent foreign-starvation probe stalled after JDI hurt returned; initial cause undetermined and no initial thread dump. It remains failed/excluded; fresh mapped recovery and two extra strict probes pass. No unrestricted no-stall/soak guarantee',
                                'General vehicle/input/flight, far/vertical/unsupported movement, arbitrary item/menu/callback and Mod payloads retain complete original serial behavior',
                                'Signed chat, chat spam counter beyond0..180, and obstructed-movement teleport corrections retain complete original server execution',
                                'Teleport/dimension/respawn/reconfiguration retain original complete transition fences; only already-applied exact matching confirmation is an owner packet',
                                'Default false and unknown installed extensions before freeze; MAIN/NETWORK original contracts unchanged; oracle never admitted to workers',
                                'Original two-client bounded installed correctness corpus; no P5 scale/performance/long-soak or graphical GUI pause certificate',
                                'Expected old injected entity boom distinguished from unexpected XP shutdown failure; original failed wrappers/verdicts and bounded-executor counterexample retained and mapped explicitly'],
                   baselineHead=subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=REPO, text=True).strip(),
                   subAgentUsed=False, p4CommitPushDeploymentPerformed=False, existingServerOperations=False)
    (output / 'receipt.json').write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + '\n')
    final = dict(status='passed', receipt=record(output / 'receipt.json'), independentVerdicts=len(verdicts),
                 installations=len(roots), acceptedCommands=len(set(accepted_commands)), closedInputs=len(inputs),
                 productionSources=len(manifest['review']['sources']), ownedServersAlive=0, p5Started=False)
    (output / 'final-audit.json').write_text(json.dumps(final, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps(final))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ['product-root', 'evidence-map', 'output']:
        parser.add_argument('--' + name, type=Path, required=True)
    audit(parser.parse_args())
